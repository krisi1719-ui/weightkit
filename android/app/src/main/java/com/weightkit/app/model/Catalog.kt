package com.weightkit.app.model

import android.content.Context
import org.json.JSONArray
import org.json.JSONObject
import kotlin.math.PI

data class Material(val id: String, val group: String, val name: String, /** kg/m³ */ val density: Double)

data class SectionItem(
    val name: String,
    val areaCm2: Double?,
    val steelKgM: Double?,
    val nominalLbFt: Double?,
    val od: Double?,
    val wall: Double?,
    val d: Double?,
) {
    /** Cross-section area in mm². */
    fun areaMM2(shape: String): Double? = when (shape) {
        "pipe" -> if (od != null && wall != null) {
            val di = od - 2 * wall
            PI / 4 * (od * od - di * di)
        } else null
        "rebar" -> d?.let { PI / 4 * it * it }
        else -> areaCm2?.let { it * 100 }
    }

    fun perimeterMM(shape: String): Double? = when (shape) {
        "pipe" -> if (od != null && wall != null) PI * od + PI * (od - 2 * wall) else null
        "rebar" -> d?.let { PI * it }
        else -> null
    }
}

data class SectionFamily(
    val id: String,
    val name: String,
    val shape: String,
    val source: String,
    val region: String,
    val pro: Boolean,
    val verified: Boolean,
    val items: List<SectionItem>,
)

/** Read-only data bundled in assets (generated by shared/build_data.py). */
class Catalog(materialsJson: String?, sectionsJson: String?) {
    constructor(ctx: Context) : this(ctx.readAsset("materials.json"), ctx.readAsset("sections.json"))

    val materials: List<Material>
    val families: List<SectionFamily>

    init {
        materials = runCatching {
            val a = JSONArray(materialsJson!!)
            (0 until a.length()).map {
                val o = a.getJSONObject(it)
                Material(o.getString("id"), o.getString("group"), o.getString("name"), o.getDouble("density"))
            }
        }.getOrElse { listOf(Material("steel", "steel", "Steel", 7850.0)) }
        families = runCatching {
            val a = JSONArray(sectionsJson!!)
            (0 until a.length()).map { i ->
                val o = a.getJSONObject(i)
                val items = o.getJSONArray("items")
                SectionFamily(
                    o.getString("id"), o.getString("name"), o.getString("shape"), o.getString("source"),
                    o.getString("region"), o.getBoolean("pro"), o.getBoolean("verified"),
                    (0 until items.length()).map { j -> item(items.getJSONObject(j)) },
                )
            }
        }.getOrElse { emptyList() }
    }

    private fun item(o: JSONObject): SectionItem {
        fun d(k: String): Double? = if (o.has(k) && !o.isNull(k)) o.getDouble(k) else null
        return SectionItem(o.getString("name"), d("area_cm2"), d("steel_kg_m"), d("nominal_lb_ft"),
            d("od"), d("wall"), d("d"))
    }

    val rebar: SectionFamily? get() = families.firstOrNull { it.id == "rebar" }
    val profileFamilies: List<SectionFamily> get() = families.filter { it.id != "rebar" }

    companion object {
        val groups = listOf("steel", "stainless", "aluminium", "copper", "other", "plastic")
    }
}

private fun Context.readAsset(name: String): String? =
    runCatching { assets.open(name).bufferedReader(Charsets.UTF_8).use { it.readText() } }.getOrNull()
