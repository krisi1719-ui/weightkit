import Foundation

struct Material: Codable, Identifiable, Hashable {
    let id: String
    let group: String
    let name: String
    /// kg/m³
    let density: Double
}

struct SectionItem: Codable, Hashable {
    let name: String
    var area_cm2: Double?
    var steel_kg_m: Double?
    var nominal_lb_ft: Double?
    var od: Double?
    var wall: Double?
    var d: Double?
    var h: Double?
    var b: Double?
    var tw: Double?
    var tf: Double?
    var r: Double?

    /// Cross-section area in mm².
    func areaMM2(shape: String) -> Double? {
        switch shape {
        case "pipe":
            guard let od, let wall else { return nil }
            let di = od - 2 * wall
            return .pi / 4 * (od * od - di * di)
        case "rebar":
            guard let d else { return nil }
            return .pi / 4 * d * d
        default:
            return area_cm2.map { $0 * 100 }
        }
    }

    func perimeterMM(shape: String) -> Double? {
        switch shape {
        case "pipe":
            guard let od, let wall else { return nil }
            return .pi * od + .pi * (od - 2 * wall)
        case "rebar":
            return d.map { .pi * $0 }
        default:
            return nil
        }
    }
}

struct SectionFamily: Codable, Identifiable, Hashable {
    let id: String
    let name: String
    let shape: String
    let source: String
    let region: String
    let pro: Bool
    let verified: Bool
    let items: [SectionItem]
}

/// Read-only data bundled with the app (generated by shared/build_data.py).
final class Catalog {
    static let shared = Catalog()
    let materials: [Material]
    let families: [SectionFamily]

    static let groups = ["steel", "stainless", "aluminium", "copper", "other", "plastic"]

    private init() {
        func load<T: Decodable>(_ name: String) -> T? {
            guard let url = Bundle.main.url(forResource: name, withExtension: "json"),
                  let data = try? Data(contentsOf: url) else { return nil }
            return try? JSONDecoder().decode(T.self, from: data)
        }
        materials = load("materials") ?? [Material(id: "steel", group: "steel", name: "Steel", density: 7850)]
        families = load("sections") ?? []
    }

    var rebar: SectionFamily? { families.first { $0.id == "rebar" } }
    var profileFamilies: [SectionFamily] { families.filter { $0.id != "rebar" } }
}
